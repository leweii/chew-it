const TABLE: Record<Lang, Dict> = { zh: ZH, en: EN };

export function t(lang: Lang, key: string, vars?: Record<string, string>): string {
  let str = TABLE[lang]?.[key] ?? ZH[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replace(`{${k}}`, vars[k]);
    }
  }
  return str;
}
